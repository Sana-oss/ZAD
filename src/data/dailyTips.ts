export const getDailyTip = (): DailyTip => {
  const dayOfYear = Math.floor(
    (Date.now() - new Date(new Date().getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24)
  );
  return dailyTips[dayOfYear % dailyTips.length];
};
